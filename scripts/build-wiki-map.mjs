#!/usr/bin/env node
/**
 * Builds src/data/wikis.json (and the Edge Function's host allow-list) from
 * Indie Wiki Buddy's open wiki list: https://github.com/KevinPayravi/indie-wiki-buddy (MIT License).
 *
 *   node scripts/build-wiki-map.mjs                 # downloads data/data.json from GitHub
 *   node scripts/build-wiki-map.mjs path/to/data.json
 */
import fs from 'node:fs';

const SRC = 'https://raw.githubusercontent.com/KevinPayravi/indie-wiki-buddy/main/data/data.json';
const raw = process.argv[2] ? fs.readFileSync(process.argv[2], 'utf8') : await (await fetch(SRC)).text();
const data = JSON.parse(raw);

/** "Elden Ring Fandom & Fextra Wikis" -> "Elden Ring" */
const stripHost = (s) =>
  s
    .replace(/\s+(Fandom|Fextralife|Fextra|Neoseeker|Wikia|Gamepedia)\b.*$/i, '')
    .replace(/\s+(Wikis?|Encyclopedia|Wikipedia)$/i, '')
    .trim();

/** "api.php" location derived from the wiki's search path ("/w/index.php" -> "/w/api.php", "/sn/" -> "/sn/api.php") */
const apiPath = (searchPath) => {
  if (/index\.php$/.test(searchPath)) return searchPath.replace(/index\.php$/, 'api.php');
  return (searchPath.endsWith('/') ? searchPath : searchPath + '/') + 'api.php';
};

const out = [];
for (const s of data.sites) {
  if (s.language !== 'EN' || s.destination_platform !== 'mediawiki') continue;
  const [host, ...rest] = s.destination_base_url.split('/');
  const basePath = rest.length ? '/' + rest.join('/') : '';
  const names = new Set([stripHost(s.origins_label), stripHost(s.destination), ...s.origins.map((o) => stripHost(o.origin))]);
  const fandom = s.origins.find((o) => /fandom\.com/.test(o.origin_base_url));
  out.push({
    id: s.id,
    keys: [...names].filter(Boolean),
    name: s.destination,
    host,
    base: `https://${s.destination_base_url}`,
    api: `https://${host}${basePath}${apiPath(s.destination_search_path)}`,
    article: `https://${s.destination_base_url}${s.destination_content_path}`,
    main: s.destination_main_page,
    official: (s.tags ?? []).includes('official'),
    fandom: fandom ? `https://${fandom.origin_base_url}` : undefined,
  });
}
out.sort((a, b) => a.id.localeCompare(b.id));

const meta = { source: 'Indie Wiki Buddy (MIT License)', url: 'https://github.com/KevinPayravi/indie-wiki-buddy', commit: data.commit, generated: data.generated };
fs.writeFileSync('src/data/wikis.json', JSON.stringify({ meta, wikis: out }));
fs.writeFileSync(
  'supabase/functions/_shared/wikiHosts.ts',
  '// Generated by scripts/build-wiki-map.mjs from Indie Wiki Buddy (MIT). Hosts the wiki proxy may contact.\n' +
    `export const WIKI_HOSTS = new Set<string>(${JSON.stringify([...new Set(out.map((w) => w.host))].sort())});\n`,
);
console.log(`wrote ${out.length} wikis (IWB commit ${data.commit})`);
